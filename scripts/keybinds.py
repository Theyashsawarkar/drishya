#!/usr/bin/env python3
"""Writes the `# keybind:` lines in <pkg>/keymap.py and the key tables in
README.md from the keymap (the one place keys are defined).

    python3 scripts/keybinds.py          rewrite both
    python3 scripts/keybinds.py --check  exit 1 if either is out of date (CI, tests)
"""
import importlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PKG = next(p.name for p in ROOT.iterdir() if (p / "keymap.py").exists())
sys.path.insert(0, str(ROOT))
keymap = importlib.import_module(f"{PKG}.keymap")

START = "# --- keybind lines: generated by scripts/keybinds.py from the tables above; don't edit ---"
END = "# --- end of keybind lines ---"
R_START = "<!-- keys: generated by scripts/keybinds.py from the keymap; don't edit by hand -->"
R_END = "<!-- end of keys -->"


def splice(text, start, end, body):
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + text[b:]


def wanted():
    km_path = ROOT / PKG / "keymap.py"
    readme = ROOT / "README.md"
    km = splice(km_path.read_text(), START, END, "\n".join(keymap.annotation_lines()) + "\n")
    rd = splice(readme.read_text(), R_START, R_END, "\n" + keymap.readme_tables() + "\n")
    return [(km_path, km), (readme, rd)]


def stale():
    return [p for p, text in wanted() if p.read_text() != text]


def main():
    if "--check" in sys.argv:
        bad = stale()
        for p in bad:
            print(f"{p.relative_to(ROOT)} is out of date: run python3 scripts/keybinds.py", file=sys.stderr)
        sys.exit(1 if bad else 0)
    for p, text in wanted():
        if p.read_text() != text:
            p.write_text(text)
            print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
